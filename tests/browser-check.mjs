import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const base=process.env.TEST_BASE_URL||'http://127.0.0.1:3000';
const out=process.env.QA_OUTPUT||'output/playwright';
await mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:1504,height:1045},serviceWorkers:'block'});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',msg=>{if(msg.type()==='error')errors.push(msg.text());});
await page.goto(base+'/user/home');
await page.getByRole('button',{name:'ดูราคาและเรียกรถ',exact:true}).waitFor();
await page.screenshot({path:out+'/desktop-th.png',fullPage:true});
assert.ok((await page.title()).includes('JUMBO GO'));
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.getByRole('button',{name:'EN',exact:true}).click();
await page.getByRole('heading',{name:'Move anything. Go anywhere.'}).waitFor();
await page.reload();
await page.getByRole('heading',{name:'Move anything. Go anywhere.'}).waitFor();
await page.screenshot({path:out+'/desktop-en.png',fullPage:true});
await page.getByPlaceholder('Enter pickup address, building or street').fill('Chatuchak, Bangkok');
