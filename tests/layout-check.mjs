import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const base=process.env.TEST_BASE_URL||'http://127.0.0.1:3000';
const out=process.env.QA_OUTPUT||'output/playwright';await mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1504,height:1045},serviceWorkers:'block'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(base+'/user/home');await page.getByRole('button',{name:'ดูราคาและเรียกรถ',exact:true}).waitFor();
await page.screenshot({path:out+'/desktop-th.png',fullPage:true});
await page.getByRole('button',{name:'EN',exact:true}).click();
await page.screenshot({path:out+'/desktop-en.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.goto(base+'/user/messages');await page.getByRole('link',{name:'Call driver in phone app'}).waitFor();
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
const input=await page.getByPlaceholder('Type a message…').boundingBox();
const nav=await page.getByRole('navigation',{name:'Mobile navigation'}).boundingBox();
assert.ok(input.y+input.height<=nav.y,'Chat input must be visible above bottom navigation');
await page.screenshot({path:out+'/chat-mobile.png',fullPage:true});
await page.goto(base+'/user/home');await page.getByRole('button',{name:'TH',exact:true}).click();await page.getByRole('button',{name:'ดูราคาและเรียกรถ',exact:true}).waitFor();
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.screenshot({path:out+'/mobile-th.png',fullPage:true});
await page.setViewportSize({width:768,height:1024});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.screenshot({path:out+'/tablet-th.png',fullPage:true});
assert.deepEqual(errors,[]);console.log('PASS: latest desktop/mobile/tablet layouts, no overflow, chat composer above mobile navigation, no runtime errors.');await browser.close();
