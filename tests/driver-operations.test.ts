import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { NextRequest } from 'next/server';
import sharp from 'sharp';
import type { Job, Session } from '../src/lib/domain';
process.env.DATABASE_PATH = ':memory:';
process.env.DEMO_MODE = 'false';
process.env.DOCUMENT_ENCRYPTION_KEY = 'd'.repeat(64);
test('driver availability, private proof, location, reconciliation and withdrawals enforce ownership and single payment', async () => {
    const { db, saveJob, getJob } = await import('../src/lib/server/db');
    const store = await import('../src/lib/server/driver-store');
    const { GET, POST } = await import('../src/app/api/driver/[...path]/route');
    const admin: Session = { id: 'admin', name: 'Admin', phone: '', role: 'admin' }, driver: Session = { id: 'driver', name: 'Driver', phone: '', role: 'driver' }, other: Session = { id: 'other', name: 'Other', phone: '', role: 'driver' }, customer: Session = { id: 'customer', name: 'Customer', phone: '0812345678', role: 'user' };
    for (const user of [admin, driver, other, customer]) {
        (await db.prepare('INSERT INTO users VALUES(?,?,?,?,0)').run(user.id, user.name, user.phone, user.role));
        (await db.prepare('INSERT INTO sessions VALUES(?,?,?)').run(user.id, user.id, Date.now() + 60000));
        if (user.role === 'driver')
            (await db.prepare('INSERT INTO driver_applications VALUES(?,?,NULL,NULL,NULL,?)').run(user.id, 'APPROVED', new Date().toISOString()));
    }
    const job: Job = { id: 'delivery', userId: customer.id, driverId: driver.id, status: 'ARRIVING', pickup: 'A', drops: ['B'], vehicle: 'pickup', fare: { base: 1000, distance: 1, distanceFee: 0, helper: 0, stops: 0, total: 1000 }, credit: 100, total: 900, note: '', scheduledAt: null, createdAt: new Date().toISOString(), history: [] };
    (await saveJob(job));
    const request = async (path: string, user: Session, body?: unknown, origin = 'http://localhost:3000') => { const req = new NextRequest('http://localhost:3000/api/driver/' + path, { method: body === undefined ? 'GET' : 'POST', headers: { host: 'localhost:3000', origin, cookie: 'jumbo_session=' + user.id, ...(body instanceof FormData ? {} : { 'content-type': 'application/json' }) }, body: body === undefined ? undefined : body instanceof FormData ? body : JSON.stringify(body) }); return (await (body === undefined ? GET : POST)(req, { params: Promise.resolve({ path: path.split('/') }) })); };
    assert.equal((await store.acceptWorkError(driver.id, 'pickup')), 'DRIVER_OFFLINE');
    (await store.updateWork(driver, { online: true, vehicle: 'pickup' }));
    assert.equal((await store.acceptWorkError(driver.id, 'box')), 'VEHICLE_MISMATCH');
    assert.equal((await store.acceptWorkError(driver.id, 'pickup')), null);
    assert.equal((await request('work', customer, { online: true, vehicle: 'pickup' })).status, 403);
    assert.equal((await request('work', driver, { online: true, vehicle: 'pickup' }, 'http://evil.example')).status, 403);
    assert.equal((await request('location/delivery', other, { lat: 13, lng: 100, accuracy: 5,consent:true })).status, 403);
    assert.equal((await request('location/delivery', driver, { lat: 91, lng: 100, accuracy: 5,consent:true })).status, 400);
    assert.equal((await request('location/delivery', driver, { lat: 13, lng: 100, accuracy: 5,consent:true, capturedAt: Date.now() - 120000 })).status, 400);
    assert.equal((await request('location/delivery', driver, { lat: 13, lng: 100, accuracy: 5 })).status, 400,'requires tracking consent');
    assert.equal((await request('location/delivery', driver, { lat: 13, lng: 100, accuracy: 5,consent:true })).status, 200);
    assert.equal((await request('location/delivery', driver, { lat: 14, lng: 100, accuracy: 5,consent:true,capturedAt:Date.now()-10000 })).status,200);
    assert.equal(Number((await db.prepare('SELECT COUNT(*) AS count FROM delivery_locations WHERE job_id=?').get(job.id))!.count),1);
    assert.equal((await request('job/delivery', other)).status, 403);
    assert.equal((await (await request('job/delivery', customer)).json()).location.lat, 13);
    const photo = await sharp({ create: { width: 20, height: 20, channels: 3, background: 'red' } }).png().toBuffer();
    const form = () => { const f = new FormData(); f.set('image', new File([new Uint8Array(photo)], 'proof.png', { type: 'image/png' })); f.set('recipient', 'Receiver'); return f; };
    assert.equal((await request('proof/delivery', driver, form())).status, 409);
    job.status = 'ARRIVED_DROPOFF';
    (await saveJob(job));
    assert.equal((await request('proof/delivery', other, form())).status, 403);
    assert.equal((await request('proof/delivery', driver, form())).status, 200);
    assert.equal((await request('proof/delivery', driver, form())).status, 409);
    assert.equal((await request('proof/delivery', other)).status, 403);
    const proof = await request('proof/delivery', customer);
    assert.equal(proof.status, 200);
    assert.equal(proof.headers.get('cache-control'), 'private, no-store');
    assert.equal(proof.headers.get('content-type'), 'image/jpeg');
    job.status = 'COMPLETED';
    (await saveJob(job));
    assert.equal((await store.jobOperations(customer, job.id)).location, null);
    assert.equal((await request('location/delivery', driver,{lat:13,lng:100,accuracy:5,consent:true})).status,409);
    (await assert.rejects(async () => (await store.settleJob(admin, { jobId: job.id, cash: 0, reference: 'receipt1' })), /PAY_POLICY_DISABLED/));
    (await assert.rejects(async () => (await store.updatePayPolicy(driver, { enabled: true, commission: 10, minimum: 100 })), /FORBIDDEN/));
    (await store.updatePayPolicy(admin, { enabled: true, commission: 10, minimum: 100 }));
    (await assert.rejects(async () => (await store.settleJob(admin, { jobId: job.id, cash: 901, reference: 'receipt1' })), /VALIDATION_ERROR/));
    (await store.settleJob(admin, { jobId: job.id, cash: 200, reference: 'receipt1' }));
    assert.equal((await store.earnings(driver.id)).available, 700);
    (await assert.rejects(async () => (await store.settleJob(admin, { jobId: job.id, cash: 0, reference: 'receipt2' })), /ALREADY_SETTLED/));
    const withdrawal = { amount: 500, bank: 'Test bank', holder: 'Driver', account: '1234567890', idem: randomUUID() };
    const id = (await store.requestWithdrawal(driver, withdrawal));
    assert.equal((await store.requestWithdrawal(driver, withdrawal)), id);
    assert.equal((await store.earnings(driver.id)).available, 200);
    (await assert.rejects(async () => (await store.requestWithdrawal(driver, { ...withdrawal, idem: randomUUID() })), /INSUFFICIENT_BALANCE/));
    (await assert.rejects(async () => (await store.requestWithdrawal(driver, { ...withdrawal, amount: 99, idem: randomUUID() })), /WITHDRAWAL_MINIMUM/));
    (await assert.rejects(async () => (await store.reviewWithdrawal(other, { id, status: 'PAID', reference: 'bank-ref', note: 'Transferred' })), /FORBIDDEN/));
    (await store.reviewWithdrawal(admin, { id, status: 'REJECTED', reference: '', note: 'Wrong bank account' }));
    assert.equal((await store.earnings(driver.id)).available, 700);
    const id2 = (await store.requestWithdrawal(driver, { ...withdrawal, idem: randomUUID() }));
    (await store.reviewWithdrawal(admin, { id: id2, status: 'PAID', reference: 'bank-reference', note: 'Verified transfer' }));
    assert.equal((await store.earnings(driver.id)).available, 200);
    (await assert.rejects(async () => (await store.reviewWithdrawal(admin, { id: id2, status: 'PAID', reference: 'bank-reference', note: 'Duplicate' })), /INVALID_TRANSITION/));
    assert.equal((await getJob(job.id))!.status, 'COMPLETED');
    assert.equal((await db.prepare('SELECT COUNT(*) n FROM ledger WHERE user_id=?').get(driver.id))!.n, 0);
    (await assert.rejects(async () => (await db.prepare('DELETE FROM driver_settlements').run()), /immutable settlement/));
});
