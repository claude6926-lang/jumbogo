import {test} from 'node:test';
import assert from 'node:assert/strict';
import type {Session} from '../src/lib/domain';
process.env.DATABASE_PATH=':memory:';process.env.TURSO_DATABASE_URL='';process.env.DEMO_MODE='false';process.env.DOCUMENT_ENCRYPTION_KEY='c'.repeat(64);
test('commission snapshots rates, requires paid completed work, isolates owners and reverses refunds without double credit',async()=>{
 const {db}=await import('../src/lib/server/db');
 const board=await import('../src/lib/server/job-board-store');const c=await import('../src/lib/server/board-commission');
 const admin:Session={id:'admin',name:'Admin',phone:'',role:'admin'},customer:Session={...admin,id:'customer',role:'user'},other:Session={...customer,id:'other'};
 for(const u of [admin,customer,other])await db.prepare('INSERT INTO users VALUES(?,?,?,?,0)').run(u.id,u.name,'',u.role);
 const input={vehicle_type:'pickup',job_type:'QA',pickup:'A',dropoff:'B',scheduled_at:new Date(Date.now()+86400000).toISOString(),helpers_count:0,price_thb:1000,allow_offers:false,contact_phone_private:'0812345678'};
 const j=await board.saveBoard(customer,input);
 assert.equal((await c.commissionSummary(customer)).pending_satang,3000);
 assert.equal((await c.commissionSummary(other)).jobs.length,0);
 await assert.rejects(()=>c.updateCommission(customer,{kind:'rate',rate:99}));
 await assert.rejects(()=>c.updateCommission(admin,{kind:'rate',rate:101}));
 await c.updateCommission(admin,{kind:'rate',rate:5});
 await board.saveBoard(customer,{...input,body_public:'edited'},j.id);
 assert.equal((await c.commissionSummary(customer)).jobs[0].rate,3);
 const j2=await board.saveBoard(customer,input);assert.equal((await c.commissionSummary(customer)).jobs.find(x=>x.id===j2.id)?.rate,5);
 const payment={kind:'payment',job_id:j.id,paid_thb:1000,reference:'BANK-TEST-1'};
 await assert.rejects(()=>c.updateCommission(admin,payment));
 await db.prepare("UPDATE board_jobs SET status='done' WHERE id IN (?,?)").run(j.id,j2.id);
 assert.equal((await c.commissionSummary(customer)).confirmed_satang,0);
 await assert.rejects(()=>c.updateCommission(customer,payment));
 await assert.rejects(()=>c.updateCommission(admin,{...payment,paid_thb:2000}));
 await Promise.all([c.updateCommission(admin,payment),c.updateCommission(admin,payment)]);
 assert.equal((await c.commissionSummary(customer)).confirmed_satang,3000);
 assert.equal((await db.prepare("SELECT id FROM audit WHERE action='BOARD_COMMISSION_PAYMENT'").all()).length,1);
 await assert.rejects(()=>c.updateCommission(admin,{...payment,job_id:j2.id}));
 await c.updateCommission(admin,{...payment,job_id:j2.id,reference:'BANK-TEST-2'});
 assert.equal((await c.commissionSummary(customer)).confirmed_satang,8000);
 await c.updateCommission(admin,{kind:'refund',job_id:j.id,refunded_thb:400,reason:'partial refund'});
 assert.equal((await c.commissionSummary(customer)).confirmed_satang,6800);
 await assert.rejects(()=>c.updateCommission(admin,{kind:'refund',job_id:j.id,refunded_thb:100,reason:'invalid reduction'}));
 await c.updateCommission(admin,{kind:'refund',job_id:j.id,refunded_thb:1000,reason:'full refund'});
 assert.equal((await c.commissionSummary(customer)).confirmed_satang,5000);
 const cancelled=await board.saveBoard(customer,input);await board.boardStatus(customer,cancelled.id,'cancelled');
 assert.equal((await c.commissionSummary(customer)).pending_satang,0);
 assert.equal((await c.commissionSummary(customer)).history.length,0);
 assert.equal(c.commissionSatang(100000,3),3000);
 assert.equal(c.commissionSatang(10001,3),300);
});
