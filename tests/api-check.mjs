// Run against an isolated DEMO_MODE server, never production data.
import assert from 'node:assert/strict';
const base=process.env.TEST_BASE_URL||'http://127.0.0.1:3001';
async function request(path,body,cookie='',extra={}){const r=await fetch(base+'/api/v1/'+path,{method:body===undefined?'GET':'POST',headers:{'content-type':'application/json',cookie,...extra},body:body===undefined?undefined:JSON.stringify(body)});return {status:r.status,data:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]};}
const guest=await request('bootstrap');assert.equal(guest.status,401);
const user=(await request('session',{role:'user'})).cookie;
const driver=(await request('session',{role:'driver'})).cookie;
const admin=(await request('session',{role:'admin'})).cookie;
assert.ok(user&&driver&&admin);
assert.equal((await request('admin/overview',undefined,user)).status,403);
assert.equal((await request('wallet/claim',{code:'JUMBO100'},user,{origin:'https://evil.example'})).status,403);
assert.equal((await request('wallet/claim',{code:'JUMBO100'},user)).data.balance,100);
assert.equal((await request('wallet/claim',{code:'JUMBO100'},user)).status,409);
const input={pickup:'Chatuchak Bangkok',drops:['Bang Na Bangkok'],vehicle:'pickup',helper:false,scheduledAt:null,note:'Handle with care',payment:'cash',useCredit:true};
const key=crypto.randomUUID();const job=(await request('jobs',input,user,{'idempotency-key':key})).data;
assert.equal(job.status,'SEARCHING');assert.equal(job.credit,100);assert.equal(job.total,372);
assert.equal((await request('jobs',input,user,{'idempotency-key':key})).data.id,job.id);
assert.equal((await request('bootstrap',undefined,user)).data.balance,0);
assert.equal((await request(`jobs/${job.id}/status`,{status:'COMPLETED'},user)).status,403);
assert.equal((await request(`jobs/${job.id}/messages`,undefined,driver)).status,403);
assert.equal((await request(`jobs/${job.id}/status`,{status:'ACCEPTED'},driver)).status,200);
assert.equal((await request(`jobs/${job.id}/messages`,{text:'Hello driver'},user)).status,201);
assert.equal((await request(`jobs/${job.id}/messages`,undefined,driver)).data[0].text,'Hello driver');
assert.equal((await request(`jobs/${job.id}/status`,{status:'COMPLETED'},driver)).status,409);
assert.equal((await request(`jobs/${job.id}/status`,{status:'CANCELLED',reason:'Test refund'},user)).status,200);
assert.equal((await request('bootstrap',undefined,user)).data.balance,100);
assert.equal((await request(`jobs/${job.id}/status`,{status:'CANCELLED',reason:'Duplicate'},user)).status,409);
assert.equal((await request('bootstrap',undefined,user)).data.balance,100);
const job2=(await request('jobs',{...input,useCredit:false},user,{'idempotency-key':crypto.randomUUID()})).data;
assert.equal((await request(`jobs/${job2.id}/status`,{status:'ACCEPTED'},driver)).status,200);
const job3=(await request('jobs',{...input,useCredit:false},user,{'idempotency-key':crypto.randomUUID()})).data;
assert.equal((await request(`jobs/${job3.id}/status`,{status:'ACCEPTED'},driver)).status,409);
for(const status of ['ARRIVING','ARRIVED_PICKUP','PICKED_UP','IN_TRANSIT','ARRIVED_DROPOFF','COMPLETED'])assert.equal((await request(`jobs/${job2.id}/status`,{status},driver)).status,200);
assert.equal((await request('admin/pricing',{id:'pickup',base:300,rate:15},user)).status,403);
assert.equal((await request('admin/pricing',{id:'pickup',base:300,rate:15},admin)).status,200);
assert.equal((await request('quote',{...input,useCredit:false},user)).data.fare.total,578);
assert.equal((await request('support',{subject:'Please help with my delivery'},user)).status,200);
const overview=(await request('admin/overview',undefined,admin)).data;
assert.equal(overview.tickets.length,1);assert.ok(overview.audit.length>10);
console.log('PASS: 29 API assertions — authorization, CSRF, credit claims, idempotency, refunds, dispatch conflicts, state transitions, chat, pricing, support and audit.');
