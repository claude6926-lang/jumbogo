import {test} from 'node:test';
import assert from 'node:assert/strict';
import {NextRequest} from 'next/server';
import {cmsSections,cmsSection,cmsIsAdvanced} from '../src/lib/cms-key';
import catalog from '../src/lib/cms/catalog.json';
test('catalog uses eight sections, preserves every key and hides technical fields',()=>{
 assert.equal(cmsSections.length,8);
 const grouped=cmsSections.flatMap(section=>catalog.filter(field=>cmsSection(field)===section));
 assert.equal(grouped.length,catalog.length);assert.equal(new Set(grouped.map(field=>field.id)).size,catalog.length);
 for(const [id,section] of [['home.17',0],['home.29',1],['vehicle.box.name',2],['home.46',3],['home.57',4],['home.75',5],['seo.title',6],['contact.email',7]] as const){assert.equal(cmsSection(catalog.find(field=>field.id===id)!),cmsSections[section]);}
 assert(catalog.filter(field=>field.type==='link').every(cmsIsAdvanced));
 assert.equal(cmsIsAdvanced(catalog.find(field=>field.id==='home.17')!),false);
 assert.equal(cmsIsAdvanced(catalog.find(field=>field.id==='home.4')!),true);
});
