process.env.DATABASE_PATH=':memory:';
process.env.DEMO_MODE='false';
test('CMS isolates drafts, authorizes writes, prevents stale saves and archives consent versions',async()=>{
 const {db}=await import('../src/lib/server/db');
 const {publishedContent,contentEditor,mutateContent,validateContent}=await import('../src/lib/server/cms-store');
 const {GET,POST}=await import('../src/app/api/content/route');
 const {createAccount}=await import('../src/lib/server/auth-store');
 for(const role of ['admin','user']){await db.prepare('INSERT INTO users VALUES(?,?,?,?,0)').run('cms-'+role,role,'',role);await db.prepare('INSERT INTO sessions VALUES(?,?,?)').run('cms-token-'+role,'cms-'+role,Date.now()+60000);}
 const req=(method:string,query='',token='',body?:unknown,origin='https://example.test')=>new NextRequest('https://example.test/api/content'+query,{method,headers:{host:'example.test',origin,cookie:token?'jumbo_session='+token:'','content-type':'application/json'},body:body?JSON.stringify(body):undefined});
 assert.equal((await GET(req('GET','?editor=1'))).status,401);
 assert.equal((await GET(req('GET','?preview=1','cms-token-user'))).status,403);
 assert.equal((await POST(req('POST','','cms-token-user',{action:'save',revision:0,values:{}}))).status,403);
 assert.equal((await POST(req('POST','','cms-token-admin',{action:'save',revision:0,values:{}},'https://evil.test'))).status,403);
 assert.throws(()=>validateContent({'home.17':'   '}));
 assert.throws(()=>validateContent({'unknown':'value'}));
 assert.throws(()=>validateContent({'brand.logo':'javascript:alert(1)'}));
 assert.throws(()=>validateContent({'brand.logo':'//evil.test/a.png'}));
 assert.throws(()=>validateContent({'brand.logo':'/\\evil.test/a.png'}));
 assert.throws(()=>validateContent({'brand.logo':'https://user:password@example.test/a.png'}));
 const values={'home.17':'CMS draft heading','contact.email':'support@example.test'};
 const saved=await mutateContent('cms-admin','save',0,values);
 assert.equal(saved.revision,1);assert.deepEqual((await publishedContent()).values,{});
 assert.deepEqual((await (await GET(req('GET','?preview=1','cms-token-admin'))).json()).values,values);
 assert.deepEqual((await (await GET(req('GET'))).json()).values,{});
 await assert.rejects(mutateContent('cms-admin','save',0,{}),/CONTENT_CHANGED/);
 const results=await Promise.allSettled([mutateContent('cms-admin','publish',1),mutateContent('cms-admin','save',1,{})]);
 assert.equal(results.filter(r=>r.status==='fulfilled').length,1);
 const live=await publishedContent();assert.equal(live.revision,2);assert.deepEqual(live.values,values);
 const input={name:'CMS consent',email:'cms-consent@example.test',phone:'0812345678',role:'user' as const};
 await assert.rejects(createAccount(input,null),/TERMS_UPDATED/);
 const id=await createAccount({...input,contentRevision:2},null);
 const consents=await db.prepare('SELECT version FROM consents WHERE user_id=?').all(id);
 assert(consents.every(row=>String(row.version).endsWith('-cms-2')));
 const editor=await contentEditor();assert.equal(editor.history.length,2);
 const restored=await mutateContent('cms-admin','restore',2,undefined,Number(editor.history[1].id));
 assert.notEqual(restored.values['home.17'],values['home.17']);assert.deepEqual((await publishedContent()).values,values);
 assert((await db.prepare("SELECT id FROM audit WHERE action LIKE 'CMS_%'").all()).length>=3);
 const {POST:upload,GET:readImage}=await import('../src/app/api/content/media/route');
 const sharp=(await import('sharp')).default;
 const png=await sharp({create:{width:20,height:20,channels:3,background:'#dc2338'}}).png().toBuffer();
 const form=new FormData();form.set('file',new File([png],'image.png',{type:'image/png'}));
 const uploaded=await upload(new NextRequest('https://example.test/api/content/media',{method:'POST',headers:{host:'example.test',origin:'https://example.test',cookie:'jumbo_session=cms-token-admin'},body:form}));
 assert.equal(uploaded.status,200);const {url}=await uploaded.json();
 const media=await readImage(new NextRequest('https://example.test'+url));assert.equal(media.status,200);assert.equal(media.headers.get('content-type'),'image/webp');assert((await media.arrayBuffer()).byteLength>0);
 const invalid=new FormData();invalid.set('file',new File(['<svg onload="alert(1)"/>'],'fake.png',{type:'image/png'}));
 assert.equal((await upload(new NextRequest('https://example.test/api/content/media',{method:'POST',headers:{host:'example.test',origin:'https://example.test',cookie:'jumbo_session=cms-token-admin'},body:invalid}))).status,400);
});
